import { update } from '@/lib/tenantResource/resource'
import { runMiddleware } from '@/util/cors'
import { NextApiRequest, NextApiResponse } from 'next'
import { auth0 } from '@/lib/auth0'

interface IBody {
	id: number
	name: string
	country_code: string
	city: string
	state: string
	address?: string
	phone_number?: string
	date_added?: Date // auto-generated by db
	description: string
	href: string
}

const EditResourceAPI = async (req: NextApiRequest, res: NextApiResponse) => {
	const session = await auth0.getSession(req)
	const user = session?.user
	await runMiddleware(req, res)

	const { body } = req as { body: IBody }

	if (user && user.role === 'ADMIN') {
		const edit = await update(body.id, body)
		res.status(edit.status).json(edit.message)
	} else {
		res.status(401).json({ error: 'UNAUTHORIZED' })
	}
}

export default auth0.withApiAuthRequired(EditResourceAPI)
